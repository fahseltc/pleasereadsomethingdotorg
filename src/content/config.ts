import { defineCollection, reference, z } from 'astro:content';
import { glob, file } from 'astro/loaders';

/**
 * Bookstore index — the single source of truth for the listing AND the map.
 * One record per store in src/content/bookstores.json (§4 of the design doc).
 *
 * Validation rules (design §10):
 *   - id, name, image, address, review are always required.
 *   - For an ENABLED store, lat/lng must be numbers (catches null geocode
 *     placeholders before they reach production). A DISABLED store may leave
 *     them null, since it ships no pin.
 *   - enabled defaults to true when absent.
 */
const bookstores = defineCollection({
  loader: file('src/content/bookstores.json'),
  schema: z
    .object({
      id: z.string(),
      name: z.string(),
      image: z.string(),
      address: z.string(),
      lat: z.number().nullable().optional(),
      lng: z.number().nullable().optional(),
      review: z.string(),
      tags: z.array(z.string()).default([]),
      website: z.string().url().optional(),
      // Optional "directions" link. Auto-generated by new:bookstore as a Google
      // Maps search for NAME + address (lands on the business, not a bare pin).
      // Override by hand with a Place ID URL for an exact match if needed.
      mapsLink: z.string().url().optional(),
      sourceAliases: z.array(z.string()).default([]),
      enabled: z.boolean().default(true),
    })
    .superRefine((store, ctx) => {
      if (store.enabled) {
        if (typeof store.lat !== 'number') {
          ctx.addIssue({
            code: z.ZodIssueCode.custom,
            path: ['lat'],
            message: `Enabled bookstore "${store.id}" needs a numeric lat (run "npm run geocode" or set enabled:false).`,
          });
        }
        if (typeof store.lng !== 'number') {
          ctx.addIssue({
            code: z.ZodIssueCode.custom,
            path: ['lng'],
            message: `Enabled bookstore "${store.id}" needs a numeric lng (run "npm run geocode" or set enabled:false).`,
          });
        }
      }
    }),
});

/**
 * Blog — one Markdown file per article in src/content/blog/.
 * `bookstore` is OPTIONAL: a post without it is a standalone article and still
 * appears in the listing (design §8). `draft: true` posts are excluded from the
 * production build.
 */
const blog = defineCollection({
  loader: glob({ pattern: '**/*.{md,mdx}', base: './src/content/blog' }),
  schema: z.object({
    title: z.string(),
    description: z.string().optional(),
    pubDate: z.coerce.date(),
    heroImage: z.string().optional(),
    // When true, a small YouTube glyph shows before the title (listing + post
    // header). Use for Shorts/video posts. Purely visual; defaults to false.
    youtube: z.boolean().default(false),
    tags: z.array(z.string()).default([]),
    bookstore: reference('bookstores').optional(),
    library: reference('libraries').optional(),
    // Optional author label (free text). Shown as a small tag on the listing and
    // the post page. Posts without it show nothing.
    author: z.string().optional(),
    // Optional ISBN-13 of the book this post is about. When set, the post shows
    // a Bookshop.org affiliate "buy" button. Hyphens/spaces are allowed; it must
    // be 13 digits once stripped (ISBN-13 always starts 978 or 979).
    isbn: z
      .string()
      .optional()
      .refine(
        (v) => v == null || /^(97[89])\d{10}$/.test(v.replace(/[\s-]/g, '')),
        { message: 'isbn must be a valid ISBN-13 (13 digits, starting 978 or 979).' },
      ),
    draft: z.boolean().default(false),
  }),
});

